QVariantMap artifactMap(const Scheme &scheme)
{
    return scheme.roles;
}

void writeText(const QString &path, const QByteArray &contents)
{
    QSaveFile file(path);
    if (!file.open(QIODevice::WriteOnly | QIODevice::Text))
        throw std::runtime_error("Cannot write " + path.toStdString());
    file.write(contents);
    if (!file.commit())
        throw std::runtime_error("Cannot commit " + path.toStdString());
}

