QString hex(uint32_t argb)
{
    return QStringLiteral("#%1").arg(argb & 0xffffffu, 6, 16, QLatin1Char('0')).toUpper();
}

Scheme schemeFor(uint32_t seed, bool dark, m3::Variant variant, double contrast)
{
    Scheme scheme;
    scheme.dark = dark;
    scheme.mode = dark ? QStringLiteral("dark") : QStringLiteral("light");
    scheme.sourceColor = hex(seed);
    scheme.contrast = contrast;
    scheme.variant = static_cast<int>(variant);
    const auto roles = m3::schemeFromArgb(seed, dark, variant, contrast);
    for (const auto &[name, argb] : roles)
        scheme.roles.insert(QString::fromStdString(name), hex(argb));
    return scheme;
}

QString ThemeService::variantName(m3::Variant variant)
{
    switch (variant) {
    case m3::Variant::kMonochrome: return QStringLiteral("monochrome");
    case m3::Variant::kNeutral: return QStringLiteral("neutral");
    case m3::Variant::kVibrant: return QStringLiteral("vibrant");
    case m3::Variant::kExpressive: return QStringLiteral("expressive");
    case m3::Variant::kFidelity: return QStringLiteral("fidelity");
    case m3::Variant::kContent: return QStringLiteral("content");
    case m3::Variant::kRainbow: return QStringLiteral("rainbow");
    case m3::Variant::kFruitSalad: return QStringLiteral("fruit-salad");
    case m3::Variant::kTonalSpot: return QStringLiteral("tonal-spot");
    }
    return QStringLiteral("tonal-spot");
}

m3::Variant ThemeService::parseVariant(const QString &name)
{
    if (name == QLatin1String("monochrome")) return m3::Variant::kMonochrome;
    if (name == QLatin1String("neutral")) return m3::Variant::kNeutral;
    if (name == QLatin1String("vibrant")) return m3::Variant::kVibrant;
    if (name == QLatin1String("expressive")) return m3::Variant::kExpressive;
    if (name == QLatin1String("fidelity")) return m3::Variant::kFidelity;
    if (name == QLatin1String("content")) return m3::Variant::kContent;
    if (name == QLatin1String("rainbow")) return m3::Variant::kRainbow;
    if (name == QLatin1String("fruit-salad")) return m3::Variant::kFruitSalad;
    return m3::Variant::kTonalSpot;
}

ThemeService::ThemeService(QString runtimeDirectory, QObject *parent)
    : ThemeService(std::move(runtimeDirectory), {}, parent)
{
}

ThemeService::ThemeService(QString runtimeDirectory, bool loadSettings, QObject *parent)
    : QObject(parent), m_directory(std::move(runtimeDirectory))
{
    QDir().mkpath(m_directory);
    if (loadSettings) {
        QSettings settings(QStringLiteral("MaterializedLinux"), QStringLiteral("theme"));
        m_variant = parseVariant(settings.value(QStringLiteral("variant"), QStringLiteral("tonal-spot")).toString());
        m_contrast = settings.value(QStringLiteral("contrast"), 0.0).toDouble();
        m_darkMode = settings.value(QStringLiteral("mode"), QStringLiteral("light")).toString() == QLatin1String("dark");
        m_auto = settings.value(QStringLiteral("mode")).toString() == QLatin1String("auto");
        m_fixedAccent = settings.value(QStringLiteral("accent"), m_fixedAccent).toUInt();
        m_wallpaper = settings.value(QStringLiteral("wallpaper")).toString();
        if (!m_wallpaper.isEmpty()) SetWallpaper(m_wallpaper, m_fit);
    }
    if (!loadSettings || m_wallpaper.isEmpty()) applySeed(m_fixedAccent, false);
}

QVariantMap ThemeService::schemeMap() const { return (m_darkMode ? m_dark : m_light).roles; }
bool ThemeService::isDark() const { return m_darkMode; }
QString ThemeService::variantName() const { return variantName(m_variant); }
double ThemeService::contrastLevel() const { return m_contrast; }
QString ThemeService::accentMode() const { return m_wallpaperAccent ? QStringLiteral("wallpaper") : QStringLiteral("fixed"); }
uint ThemeService::accentColor() const { return m_wallpaperAccent ? m_wallpaperAccentColor : m_fixedAccent; }
QString ThemeService::mode() const { return m_auto ? QStringLiteral("auto") : (m_darkMode ? QStringLiteral("dark") : QStringLiteral("light")); }
QString ThemeService::outputDirectory() const { return m_directory; }

void ThemeService::applySeed(uint32_t seed, bool persist)
{
    m_wallpaperAccentColor = m_wallpaperAccent ? seed : m_fixedAccent;
    m_light = schemeFor(seed, false, m_variant, m_contrast);
    m_dark = schemeFor(seed, true, m_variant, m_contrast);
    if (persist) {
        QSettings settings(QStringLiteral("MaterializedLinux"), QStringLiteral("theme"));
        settings.setValue(QStringLiteral("variant"), variantName());
        settings.setValue(QStringLiteral("contrast"), m_contrast);
        settings.setValue(QStringLiteral("mode"), mode());
        settings.setValue(QStringLiteral("accent"), m_fixedAccent);
        settings.setValue(QStringLiteral("wallpaper"), m_wallpaper);
    }
    if (writeArtifacts()) {
        const auto &scheme = m_darkMode ? m_dark : m_light;
        const QString path = m_directory + QStringLiteral("/scheme-%1.json").arg(scheme.mode);
        qputenv("MAT_SCHEME_PATH", path.toUtf8());
        emit SchemeChanged(scheme.roles, path);
    }
}

void ThemeService::generate() { applySeed(m_wallpaperAccent ? m_wallpaperAccentColor : m_fixedAccent, false); }

void ThemeService::setOptions(m3::Variant variant, double contrast, uint fixedAccent, bool wallpaper)
{
    m_variant = variant;
    m_contrast = contrast;
    m_fixedAccent = fixedAccent;
    m_wallpaperAccent = wallpaper;
    m_wallpaperAccentColor = fixedAccent;
    applySeed(fixedAccent, false);
}

void ThemeService::SetMode(const QString &mode)
{
    if (mode != QLatin1String("light") && mode != QLatin1String("dark") && mode != QLatin1String("auto")) {
        if (calledFromDBus()) sendErrorReply(QDBusError::InvalidArgs, QStringLiteral("Mode must be light, dark or auto"));
        return;
        return;
    }
    m_auto = mode == QLatin1String("auto");
    m_darkMode = mode == QLatin1String("dark");
    if (m_auto) {
        const int hour = QTime::currentTime().hour();
        m_darkMode = hour >= 19 || hour < 7;
    }
    applySeed(m_wallpaperAccent ? m_wallpaperAccentColor : m_fixedAccent);
}

void ThemeService::SetVariant(const QString &variant)
{
    const QStringList variants = {QStringLiteral("tonal-spot"), QStringLiteral("monochrome"), QStringLiteral("neutral"),
        QStringLiteral("vibrant"), QStringLiteral("expressive"), QStringLiteral("fidelity"), QStringLiteral("content"),
        QStringLiteral("rainbow"), QStringLiteral("fruit-salad")};
    if (!variants.contains(variant)) {
        sendErrorReply(QDBusError::InvalidArgs, QStringLiteral("Unknown Material 3 variant"));
        return;
    }
    m_variant = parseVariant(variant);
    applySeed(m_wallpaperAccent ? m_wallpaperAccentColor : m_fixedAccent);
}

void ThemeService::SetContrast(double level)
{
    if (level < -1.0 || level > 1.0) {
        sendErrorReply(QDBusError::InvalidArgs, QStringLiteral("Contrast must be in [-1, 1]"));
        return;
    }
    m_contrast = level;
    applySeed(m_wallpaperAccent ? m_wallpaperAccentColor : m_fixedAccent);
}

void ThemeService::SetAccent(const QVariantMap &spec)
{
    const QString mode = spec.value(QStringLiteral("mode"), QStringLiteral("fixed")).toString();
    const QString color = spec.value(QStringLiteral("argb")).toString();
    if (mode == QLatin1String("wallpaper")) {
        m_wallpaperAccent = true;
        if (!m_wallpaper.isEmpty()) SetWallpaper(m_wallpaper, m_fit);
        else applySeed(m_wallpaperAccentColor);
        return;
    }
    if (color.startsWith(QLatin1Char('#'))) {
        bool valid = false;
        const uint argb = color.mid(1).toUInt(&valid, 16);
        if (!valid || (color.size() != 7 && color.size() != 9)) {
            sendErrorReply(QDBusError::InvalidArgs, QStringLiteral("Expected #RRGGBB or #AARRGGBB"));
            return;
        }
        m_fixedAccent = 0xff000000u | (argb & 0xffffffu);
    }
    m_wallpaperAccent = false;
    applySeed(m_fixedAccent);
}

void ThemeService::SetWallpaper(const QString &path, const QString &fit)
{
    QImage source(path);
    if (source.isNull()) {
        sendErrorReply(QDBusError::InvalidArgs, QStringLiteral("Cannot decode wallpaper: %1").arg(path));
        return;
    }
    m_wallpaper = path;
    m_fit = fit;
    m_wallpaperAccent = true;
    const QImage image = source.convertToFormat(QImage::Format_ARGB32).scaled(128, 128, Qt::KeepAspectRatio, Qt::SmoothTransformation);
    std::vector<uint32_t> pixels;
    pixels.reserve(static_cast<std::size_t>(image.width() * image.height()));
    for (int y = 0; y < image.height(); ++y) {
        for (int x = 0; x < image.width(); ++x) {
            const QRgb color = image.pixel(x, y);
            if (qAlpha(color) > 128) pixels.push_back(color);
        }
    }
    const uint32_t seed = pixels.empty() ? m_fixedAccent : m3::sourceColorFromImage(pixels);
    applySeed(seed);
    emit WallpaperChanged(path, {{QStringLiteral("seed"), hex(seed)}, {QStringLiteral("fit"), fit}, {QStringLiteral("width"), source.width()}, {QStringLiteral("height"), source.height()}});
}

void ThemeService::Preview(const QVariantMap &scheme)
{
    (void)scheme;
    // Previews are intentionally opt-in and bounded. No permanent state changes.
    emit SchemeChanged(scheme, m_directory + QStringLiteral("/scheme-%1.json").arg(m_darkMode ? QStringLiteral("dark") : QStringLiteral("light")));
}

void ThemeService::Restore() { generate(); }
void ThemeService::Reload() { generate(); }

bool ThemeService::writeArtifacts()
{
    QDir().mkpath(m_directory);
    for (const auto &scheme : {m_light, m_dark}) {
        QJsonObject root;
        root.insert(QStringLiteral("schemaVersion"), 1);
        root.insert(QStringLiteral("mode"), scheme.mode);
        root.insert(QStringLiteral("dark"), scheme.dark);
        root.insert(QStringLiteral("sourceColor"), scheme.sourceColor);
        root.insert(QStringLiteral("contrast"), scheme.contrast);
        root.insert(QStringLiteral("variant"), variantName(static_cast<m3::Variant>(scheme.variant)));
        root.insert(QStringLiteral("roles"), QJsonObject::fromVariantMap(scheme.roles));
        const QString path = m_directory + QStringLiteral("/scheme-%1.json").arg(scheme.mode);
        writeText(path, QJsonDocument(root).toJson(QJsonDocument::Compact) + "\n");
        writeText(m_directory + QStringLiteral("/scheme-%1.qml").arg(scheme.mode), lightQml(scheme).toUtf8());
        writeText(m_directory + QStringLiteral("/gtk-%1.css").arg(scheme.mode), gtkCss(scheme).toUtf8());
        writeText(m_directory + QStringLiteral("/firefox-userChrome-%1.css").arg(scheme.mode), firefoxUserChrome(scheme).toUtf8());
        writeText(m_directory + QStringLiteral("/xrdb-%1").arg(scheme.mode),
                  QStringLiteral("*.background: %1\n*.foreground: %2\n*.color0: %3\n*.color8: %4\n*.color12: %5\n")
                  .arg(scheme.roles[QStringLiteral("background")].toString(), scheme.roles[QStringLiteral("foreground")].toString(),
                       scheme.roles[QStringLiteral("surfaceContainerLowest")].toString(), scheme.roles[QStringLiteral("surfaceVariant")].toString(),
                       scheme.roles[QStringLiteral("primary")].toString()).toUtf8());
    }
    writeText(m_directory + QStringLiteral("/current-mode"), (m_darkMode ? QByteArray("dark\n") : QByteArray("light\n")));
    writeText(m_directory + QStringLiteral("/theme.qml"), lightQml(m_darkMode ? m_dark : m_light).toUtf8());
    writeText(m_directory + QStringLiteral("/gtk.css"), gtkCss(m_darkMode ? m_dark : m_light).toUtf8());
    writeText(m_directory + QStringLiteral("/firefox-userChrome.css"), firefoxUserChrome(m_darkMode ? m_dark : m_light).toUtf8());
    return true;
}

