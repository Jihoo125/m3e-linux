QString lightQml(const Scheme &scheme)
{
    QString result = QStringLiteral("// Generated by matsessiond; do not edit.\npragma Singleton\nimport QtQuick\nQtObject {\n");
    for (auto it = scheme.roles.cbegin(); it != scheme.roles.cend(); ++it)
        result += QStringLiteral("    readonly property color %1: \"%2\"\n").arg(it.key(), it.value().toString());
    result += QStringLiteral("}\n");
    return result;
}

QString gtkCss(const Scheme &scheme)
{
    QString result = QStringLiteral("/* Generated Materialized Material 3 GTK palette */\n@define-color accent_color %1;\n@define-color accent_bg_color %1;\n@define-color accent_fg_color %2;\n@define-color window_bg_color %3;\n@define-color window_fg_color %4;\n@define-color view_bg_color %5;\n@define-color view_fg_color %4;\n@define-color headerbar_bg_color %6;\n@define-color headerbar_fg_color %4;\n@define-color card_bg_color %7;\n@define-color card_fg_color %4;\n@define-color dialog_bg_color %6;\n@define-color dialog_fg_color %4;\n@define-color popover_bg_color %6;\n@define-color popover_fg_color %4;\n@define-color sidebar_bg_color %5;\n@define-color sidebar_fg_color %4;\n@define-color error_bg_color %8;\n@define-color error_fg_color %9;\n")
        .arg(scheme.roles.value(QStringLiteral("primary")).toString(),
             scheme.roles.value(QStringLiteral("onPrimary")).toString(),
             scheme.roles.value(QStringLiteral("background")).toString(),
             scheme.roles.value(QStringLiteral("onBackground")).toString(),
             scheme.roles.value(QStringLiteral("surfaceContainerLow")).toString(),
             scheme.roles.value(QStringLiteral("surfaceContainer")).toString(),
             scheme.roles.value(QStringLiteral("surfaceContainerHigh")).toString(),
             scheme.roles.value(QStringLiteral("error")).toString(),
             scheme.roles.value(QStringLiteral("onError")).toString());
    return result;
}

QString firefoxUserChrome(const Scheme &scheme)
{
    // Real Firefox chrome theming: applied via userChrome.css in a dedicated
    // profile (toolkit.legacyUserProfileCustomizations.stylesheets).
    const QString bg = scheme.roles.value(QStringLiteral("surfaceContainer")).toString();
    const QString fg = scheme.roles.value(QStringLiteral("onSurface")).toString();
    const QString accent = scheme.roles.value(QStringLiteral("primary")).toString();
    const QString onAccent = scheme.roles.value(QStringLiteral("onPrimary")).toString();
    const QString field = scheme.roles.value(QStringLiteral("surfaceContainerHighest")).toString();
    return QStringLiteral(
        "/* Generated by matsessiond from the live Material 3 scheme. */\n"
        ":root { --mat-bg: %1; --mat-fg: %2; --mat-accent: %3; --mat-on-accent: %4; --mat-field: %5; }\n"
        "#navigator-toolbox { background: var(--mat-bg) !important; color: var(--mat-fg) !important; }\n"
        "#nav-bar, #TabsToolbar, #PersonalToolbar { background: var(--mat-bg) !important; color: var(--mat-fg) !important; }\n"
        "#urlbar-background, #searchbar .searchbar-textbox { background: var(--mat-field) !important; color: var(--mat-fg) !important; border-radius: 20px !important; }\n"
        ".tabbrowser-tab[selected=\"true\"] .tab-background { background: var(--mat-accent) !important; }\n"
        ".tabbrowser-tab[selected=\"true\"] .tab-label { color: var(--mat-on-accent) !important; }\n"
        ".tabbrowser-tab .tab-label { color: var(--mat-fg) !important; }\n"
        "#urlbar-input, .searchbar-textbox input { color: var(--mat-fg) !important; }\n"
        "toolbarbutton:hover { background: var(--mat-field) !important; border-radius: 12px !important; }\n")
        .arg(bg, fg, accent, onAccent, field);
}

